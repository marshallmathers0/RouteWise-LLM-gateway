"""Measure the gateway's own overhead under modest concurrency, honestly.

1. Start uvicorn with ROUTEWISE_MOCK_PROVIDERS=1 (instant canned LLM), a fresh SQLite log
   DB and a fresh semantic cache, so the numbers are the gateway's cost, not the model's.
2. Run Locust headless (default 10 users for 60 s).
3. Report client-side latency (Locust) and server-side overhead = total - llm, per path.

Run:  python -m eval.load_test [--users 10 --duration 60]
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import httpx
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "reports" / "load_test.md"


def run_scenario(users: int, spawn_rate: float, duration: int, port: int) -> tuple[pd.DataFrame, pd.DataFrame, dict]:
    """Fresh server (fresh cache + log DB) per scenario so scenarios don't affect each other."""
    tmp = Path(tempfile.mkdtemp(prefix="rw_load_"))
    cfg_text = (ROOT / "config" / "routewise.yaml").read_text(encoding="utf-8")
    cfg_text = cfg_text.replace("semantic_db_path: data/semantic_cache.db", f"semantic_db_path: {(tmp / 'sem.db').as_posix()}")
    # Load test measures latency, not quotas: lift the per-key rate limit.
    cfg_text = cfg_text.replace("capacity: 30 ", "capacity: 1000000 ").replace("refill_per_second: 0.5", "refill_per_second: 100000")
    (tmp / "cfg.yaml").write_text(cfg_text, encoding="utf-8")
    env = {**os.environ, "ROUTEWISE_MOCK_PROVIDERS": "1", "ROUTEWISE_CONFIG": str(tmp / "cfg.yaml"),
           "DATABASE_URL": f"sqlite:///{(tmp / 'logs.db').as_posix()}", "REDIS_URL": os.environ.get("LOADTEST_REDIS_URL", ""),
           "LOADTEST_SAMPLES": str(tmp / "samples.jsonl")}
    server = subprocess.Popen([sys.executable, "-m", "uvicorn", "routewise.main:app", "--port", str(port),
                               "--log-level", "warning"], cwd=ROOT, env=env)
    try:
        for _ in range(120):
            try:
                if httpx.get(f"http://127.0.0.1:{port}/health", timeout=1).status_code == 200:
                    break
            except httpx.HTTPError:
                time.sleep(1)
        else:
            raise SystemExit("server did not start")
        health = httpx.get(f"http://127.0.0.1:{port}/health").json()
        subprocess.run([sys.executable, "-m", "locust", "-f", str(ROOT / "eval" / "loadtest" / "locustfile.py"),
                        "--headless", "-u", str(users), "-r", str(spawn_rate), "-t", f"{duration}s",
                        "--host", f"http://127.0.0.1:{port}", "--csv", str(tmp / "locust"), "--only-summary"],
                       cwd=ROOT, env=env, check=False)
    finally:
        server.terminate()
        server.wait(timeout=30)
    stats = pd.read_csv(tmp / "locust_stats.csv")
    samples = pd.read_json(tmp / "samples.jsonl", lines=True)
    samples["overhead"] = samples["total"] - samples["llm"]
    return stats, samples, health


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--users", type=int, default=10)
    ap.add_argument("--spawn-rate", type=float, default=5)
    ap.add_argument("--duration", type=int, default=60)
    ap.add_argument("--port", type=int, default=8077)
    args = ap.parse_args()
    # 1 user = the per-request cost with no contention; N users = behaviour under load.
    results = {n: run_scenario(n, args.spawn_rate, args.duration, args.port) for n in (1, args.users)}
    write_report(args, results)
    print(f"wrote {REPORT}")


def write_report(args, results: dict) -> None:
    L: list[str] = []
    w = L.append
    health = next(iter(results.values()))[2]
    w("# Gateway load test\n")
    w("_Generated by `python -m eval.load_test`. Providers are MOCKED (instant canned answers), so these numbers "
      "are RouteWise's own overhead, not LLM latency._\n")
    w(f"* Two scenarios of {args.duration} s each: 1 user (no contention) and {args.users} concurrent users. "
      f"Single uvicorn worker on a laptop CPU, Redis {'on' if health.get('redis') else 'off'}, "
      f"semantic cache {'on' if health.get('semantic_cache') else 'off'}, SQLite request logs.")
    w("* Mix per user: 3x new questions (cache-miss path: embedding, FAISS, guards, verifier, router, mock LLM, "
      "logging) to 1x repeated questions (semantic-hit path).\n")
    w("## Client-side latency and throughput (Locust)\n")
    w("| Users | Request | Requests | Failures | Throughput (req/s) | p50 (ms) | p95 (ms) | p99 (ms) |")
    w("|---|---|---|---|---|---|---|---|")
    for users, (stats, _, _) in results.items():
        for _, r in stats.iterrows():
            w(f"| {users} | {r['Name']} | {int(r['Request Count'])} | {int(r['Failure Count'])} | {r['Requests/s']:.1f} | "
              f"{r['50%']:.0f} | {r['95%']:.0f} | {r['99%']:.0f} |")
    w("\n## Server-side gateway time excluding the (mock) LLM call, from RouteWise metadata\n")
    w("| Users | Path | n | p50 (ms) | p95 (ms) |")
    w("|---|---|---|---|---|")
    for users, (_, samples, _) in results.items():
        for status, g in samples.groupby("cache"):
            w(f"| {users} | {status} | {len(g)} | {np.percentile(g['overhead'], 50):.1f} | "
              f"{np.percentile(g['overhead'], 95):.1f} |")
    w("\n## Reading it honestly\n")
    w("* The **1-user** rows are the real per-request cost of RouteWise's pipeline on CPU. It is dominated by the "
      "two transformer models (bi-encoder embedding + cross-encoder verifier).")
    w("* Under concurrency the server-side times grow too: they are wall-clock times that include waiting for the "
      "shared CPU (one worker, model inference in a thread pool, torch threads competing). Throughput, not "
      "per-request work, is the limit; more workers, batching across requests, or a GPU would raise it.")
    w("* Relative to a real LLM call (seconds on the free tiers used in this project) the single-user overhead is "
      "small, and a cache hit replaces the LLM call entirely.")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")




if __name__ == "__main__":
    main()
