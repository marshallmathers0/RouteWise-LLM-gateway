"""Write the router's real results into README, REPORT and DEVLOG, plus resume bullets.

Runs automatically as the last step of `start_router_training.bat` (after training and
evaluation), and can be re-run any time:   python scripts/finalize_router_results.py

Reads only generated reports (reports/router_eval.json, reports/cache_eval.json,
reports/load_test.md), so every number it writes comes from code that actually ran.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def replace_between(path: Path, start: str, end: str, body: str) -> None:
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    if not pattern.search(text):
        raise SystemExit(f"markers {start} / {end} not found in {path.name}")
    path.write_text(pattern.sub(lambda _: f"{start}\n{body.strip()}\n{end}", text, count=1), encoding="utf-8")


def replace_section(path: Path, heading: str, next_heading: str, body: str) -> None:
    text = path.read_text(encoding="utf-8")
    i, j = text.find(heading), text.find(next_heading)
    if i < 0 or j < 0 or j < i:
        raise SystemExit(f"section {heading!r} not found in {path.name}")
    path.write_text(text[:i] + heading + "\n\n" + body.strip() + "\n\n" + text[j:], encoding="utf-8")


def main() -> None:
    ev_path = REPORTS / "router_eval.json"
    if not ev_path.exists():
        sys.exit("reports/router_eval.json not found: run the router pipeline first")
    ev = json.loads(ev_path.read_text(encoding="utf-8"))
    h, models = ev["headline"], ev["models"]
    chosen = h["chosen"]
    met = "met" if h["meets_target"] else "**not met**"
    auc = models[chosen]["roc_auc"]
    cache = json.loads((REPORTS / "cache_eval.json").read_text(encoding="utf-8"))
    deployed = cache["operating_points"]["all three"]["test"]["all"]
    matched = cache["matched_cosine_only"]["test"]["all"]
    load = (REPORTS / "load_test.md").read_text(encoding="utf-8")
    m = re.search(r"\| 1 \| miss \| \d+ \| ([\d.]+) \| ([\d.]+) \|", load)
    p50, p95 = (m.group(1), m.group(2)) if m else ("?", "?")

    rows = "\n".join(
        f"| {name}{' (chosen)' if name == chosen else ''} | {pct(r['quality'] / h['always_strong_quality'])} | "
        f"{pct(1 - r['cost'] / ev['always_strong_cost_usd'])} | {r['roc_auc']:.3f} |"
        for name, r in models.items())
    table = f"""| Policy (test split, {ev['test_n']} queries) | Quality vs always-strong | Est. cost saved | ROC-AUC |
|---|---|---|---|
| always-strong (`{ev['models_used']['strong']}`) | 100.0% | 0.0% | |
| always-cheap (`{ev['models_used']['cheap']}`) | {pct(h['always_cheap_quality_frac'])} | {pct(h['always_cheap_cost_saved'])} | |
| length heuristic (rule-based) | {pct(h['length_quality_frac'])} | {pct(h['length_cost_saved'])} | |
| random routing at the chosen router's cost | {pct(h['random_quality_frac_at_chosen_cost'])} | {pct(h['chosen_cost_saved'])} | |
{rows}
| oracle (perfect labels, upper bound) | {pct(h['oracle_quality_frac'])} | {pct(h['oracle_cost_saved'])} | |"""
    headline = (f"The learned router (**{chosen}**, threshold chosen on validation) saved **{pct(h['chosen_cost_saved'])}** "
                f"of estimated cost versus always-strong while keeping **{pct(h['chosen_quality_frac'])}** of its quality "
                f"on the held-out test split (target 95%: {met}). Router inference: "
                f"{ev['latency_ms']['p50_ms']:.0f} ms p50 on CPU.")

    replace_between(ROOT / "README.md", "<!-- ROUTER_RESULTS_START -->", "<!-- ROUTER_RESULTS_END -->",
                    f"**Learned router** ([reports/router_eval.md](reports/router_eval.md)): {headline}\n\n{table}\n\n"
                    "The two tiers differ in price by only 2x, so no router can save much more than ~50% here; "
                    "the test split is small, so differences of a few points are within noise.")
    replace_between(ROOT / "REPORT.md", "<!-- ROUTER_REPORT_START -->", "<!-- ROUTER_REPORT_END -->",
                    f"{headline}\n\n{table}\n\nFull details - label balance, judge validation, per-source results, "
                    "leave-one-source-out AUC - are in `reports/router_eval.md` and `reports/router_labels.md`.")
    replace_section(ROOT / "DEVLOG.md", "### 3.4 Router", "### 3.5 Test suite",
                    f"{headline}\n\n{table}\n\nSource: `reports/router_eval.md` (generated by `python -m eval.router_eval`).")

    bullets = f"""# Resume bullets (generated from reports/ - every number comes from code that ran)

- Built **RouteWise**, an OpenAI-compatible LLM gateway (FastAPI, Redis, SQLAlchemy) with retries, per-tier
  fallback chains, per-model circuit breakers and a cost guard; {p50} ms p50 / {p95} ms p95 gateway overhead
  on CPU, measured with Locust.
- Designed a **verified semantic cache** (bge-small embeddings + FAISS, rule guards, cross-encoder verifier):
  on a 2,300-pair adversarial benchmark it cut wrong cache hits from {pct(matched['false_hit_rate'])} to
  {pct(deployed['false_hit_rate'])} at the same {pct(deployed['hit_rate'])} hit rate versus cosine-only caching.
- Trained a **learned cheap/strong LLM router** (LogReg / LightGBM / MLP on query embeddings + handcrafted
  features; labels from ground truth and a cross-family LLM judge) that saved {pct(h['chosen_cost_saved'])} of
  estimated cost while keeping {pct(h['chosen_quality_frac'])} of strong-model quality on held-out data
  (ROC-AUC {auc:.2f}); experiments tracked and models versioned in MLflow, tests run in GitHub Actions CI.
"""
    (REPORTS / "resume_bullets.md").write_text(bullets, encoding="utf-8")
    print(headline)
    print("updated README.md, REPORT.md, DEVLOG.md and wrote reports/resume_bullets.md")


if __name__ == "__main__":
    main()
